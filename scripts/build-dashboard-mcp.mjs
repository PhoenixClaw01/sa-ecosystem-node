import { createHash } from "node:crypto";
import { copyFileSync, lstatSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import path from "node:path";

import * as esbuild from "esbuild";

const nodeBuiltins = new Set(builtinModules.flatMap((name) => [name, `node:${name}`]));

const outfile = "dashboard/api/mcp.js";
const scripts = {
  "ata.js": readFileSync("dashboard/ata.js", "utf8"),
  "squads.js": readFileSync("dashboard/squads.js", "utf8"),
};
const signerSource = "hub/signers.json";
const signerSha = createHash("sha256").update(readFileSync(signerSource)).digest("hex");
// Extra signer-set files shipped beside hub/signers.json. Each is copied byte for byte and pinned by sha256.
const signerSetSources = ["hub/signers/agents.json"];
const signerSetShas = signerSetSources.map((file) => createHash("sha256").update(readFileSync(file)).digest("hex"));
const banner = [
  `globalThis.__SA_DASHBOARD_SCRIPTS=${JSON.stringify(scripts)};`,
  `globalThis.__SA_SIGNERS_SHA256=${JSON.stringify(signerSha)};`,
  `globalThis.__SA_SIGNER_SET_SHA256S=${JSON.stringify(signerSetShas)};`,
  "/* Generated by npm run build:dashboard-mcp. Do not edit. */",
].join("\n");

const signersPinBundle = path.resolve("src/hub/signers-pin-bundle.ts");

await esbuild.build({
  entryPoints: ["src/public-mcp-entry.ts"],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  legalComments: "none",
  outfile,
  banner: { js: banner },
  define: {
    __SA_SIGNERS_SHA256_DEFINE__: JSON.stringify(signerSha),
    // A JSON string, so esbuild inlines it as a literal instead of injecting an array module.
    __SA_SIGNER_SET_SHA256S_DEFINE__: JSON.stringify(JSON.stringify(signerSetShas)),
  },
  plugins: [
    {
      name: "signers-pin",
      setup(build) {
        build.onResolve({ filter: /signers-pin\.js$/ }, () => ({ path: signersPinBundle }));
      },
    },
  ],
});

const text = readFileSync(outfile, "utf8");
const external = [...text.matchAll(/from\s+"([^"]+)"/g)]
  .map((match) => match[1])
  .filter((specifier) => !nodeBuiltins.has(specifier));
if (external.length > 0) {
  console.error(`Bundle still imports packages: ${external.join(", ")}`);
  process.exit(1);
}

const exported = text.match(/export \{\n {2}(\w+) as default\n\};\s*$/);
if (!exported) {
  console.error("esbuild did not end with a single default export.");
  process.exit(1);
}
writeFileSync(outfile, text.replace(exported[0], `export default ${exported[1]};\n`));
console.log(`Wrote ${outfile}`);

const signerCopy = "dashboard/hub/signers.json";
mkdirSync("dashboard/hub", { recursive: true });
try {
  if (lstatSync(signerCopy).isSymbolicLink()) rmSync(signerCopy);
} catch {
  // The copy is absent until the first build.
}
copyFileSync(signerSource, signerCopy);
const sourceBytes = readFileSync(signerSource);
const copyBytes = readFileSync(signerCopy);
if (!sourceBytes.equals(copyBytes) || lstatSync(signerCopy).isSymbolicLink()) {
  console.error("dashboard/hub/signers.json is not a byte copy of hub/signers.json.");
  process.exit(1);
}
console.log(`Wrote ${signerCopy}`);

for (const source of signerSetSources) {
  const copy = path.join("dashboard", source);
  mkdirSync(path.dirname(copy), { recursive: true });
  try {
    if (lstatSync(copy).isSymbolicLink()) rmSync(copy);
  } catch {
    // The copy is absent until the first build.
  }
  copyFileSync(source, copy);
  if (!readFileSync(source).equals(readFileSync(copy)) || lstatSync(copy).isSymbolicLink()) {
    console.error(`${copy} is not a byte copy of ${source}.`);
    process.exit(1);
  }
  console.log(`Wrote ${copy}`);
}
